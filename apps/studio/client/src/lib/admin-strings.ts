export function ad(): AdminStrings {
  return i18n.lang === 'da' ? da : en
}

export const afill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))

/** A refusal code from the server as a sentence (or the generic one with the code). */
export function codeText(code: string | undefined): string {
  const s = ad()
  if (code === 'cancelled') return s.errCancelled
  if (code === 'other' || !code) return s.errGeneric
  return s.code[code] ?? afill(s.errCode, { code })
}
