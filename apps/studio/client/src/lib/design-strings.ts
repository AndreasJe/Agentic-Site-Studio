export function ds(): Strings {
  return i18n.lang === 'da' ? da : en
}

export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))

/** A server refusal as a plain sentence. */
export function refusal(body: Record<string, unknown>): string {
  const s = ds()
  const code = typeof body.code === 'string' ? body.code : ''
  const template = s.err[code]
  if (!template) return s.errGeneric
  const strs = (v: unknown) => (Array.isArray(v) ? v.map(String) : [])
  return fill(template, {
    count: typeof body.count === 'number' ? body.count : 0,
    missing: strs(body.missing)
      .map((m) => s.checks[m] ?? m)
      .join(', '),
    reasons: strs(body.reasons).join(' '),
    issues: Array.isArray(body.issues)
      ? body.issues.map((i) => (i as { message?: string }).message ?? '').join(' ')
      : '',
  })
}
