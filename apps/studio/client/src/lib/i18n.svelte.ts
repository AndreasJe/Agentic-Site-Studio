const catalogue: Record<Lang, Record<Key, string>> = { en, da }

export const i18n = $state<{ lang: Lang }>({ lang: 'en' })

export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return catalogue[i18n.lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ''))
}

/** The signed-in person's saved language wins; call this when /api/me answers. */
export function adoptLanguage(lang: Lang) {
  i18n.lang = lang
  document.documentElement.lang = lang
}

/** `signedIn`: also remember the choice for this person (POST /api/me/language). */
export async function setLanguage(lang: Lang, signedIn: boolean) {
  adoptLanguage(lang)
  if (signedIn) await api('POST', '/api/me/language', { language: lang })
}
